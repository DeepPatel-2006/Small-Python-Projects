def find_mutual_friend(self_user: str, friend_user: str, social_dict: dict) -> int:
    """
        returns the number of friends a given user and a friend in their friend list have

        Args:
            self_user (str): the username of the input user
            friend_user (str): a given friend in the user's friend list
            social_dict (dict): the input dictionary
        
        Returns:
            mutual_friends (int): the amount of mutual friends self_user and friend_user have
    """
    assert type(self_user) == str
    assert type(friend_user) == str
    assert type(social_dict) == dict
    
    self_friend_list = social_dict[self_user]['friends']
    friend_friend_list = social_dict[friend_user]['friends']
    mutual_friends = 0
    
    for friend in self_friend_list:
        if friend in friend_friend_list:
            mutual_friends += 1
        

    return mutual_friends


