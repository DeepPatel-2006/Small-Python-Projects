def get_level_friends(self_user: str, self_pass: str, social_dict: dict, level: int) -> int | list:
    """
        returns a list of all the users that are a certain level of mutuality away from the given input user

        Args:
            self_user (str): the username of the input user
            self_pass (str): the password of the input user
            social_dict (dict): the input dictionary
            level (int): the given input level
        
        Returns:
            level_list (list): the list that contains all of the users in the dictionary that are a current level of mutuality away from the given input user
    """
    assert type(self_user) == str
    assert type(self_pass) == str
    assert type(social_dict) == dict
    assert type(level) == int
    
    if authenticate_user(self_user, self_pass, social_dict) == False:
        print(error_to_string(ERROR_FAILED_AUTHENTICATION))
        return ERROR_FAILED_AUTHENTICATION
    

    level_list = []
    queue = []
    distances = {}
    distances[self_user] = 0
    queue.append(self_user)
    while queue:
        current_user = queue[0]
        del queue[0]
        for friend in social_dict[current_user]['friends']:
            if friend in distances:
                if distances[friend] > (distances[current_user] + 1):
                    distances[friend] = (distances[current_user] + 1)
            else:
                queue.append(friend)
                distances[friend] = distances[current_user] + 1

    for key in distances:
        if distances[key] == level:
            level_list.append(key)


    return level_list

