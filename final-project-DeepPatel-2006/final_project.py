def get_countries(self_user: str, social_dict: dict) -> dict:
    """
        returns the freuquence of the countries of a user's friend list

        Args:
            self_user (str): the username of the input user
            social_dict (dict): the input dictionary
        
        Returns:
            countries_dict (dict): the dictionary which keys of countries and values of the frequency at which the countries appead in a user's friend list
    """
    assert type(self_user) == str
    assert type(social_dict) == dict

    countries_dict = {}
    friends_list = social_dict[self_user]['friends']
    for friend in friends_list:

        country = get_user_country(friend, social_dict)

        if country not in countries_dict:
            countries_dict[country] = 1
        else:
            countries_dict[country] += 1

    return countries_dict



