def encrypt_password(password: str) -> str:
    """
        encrypts a password using caeser cipher method

        Args:
            password (str): the plain text password
        
        Returns:
            final_password (str): the encrypted password
    """
    assert type(password) == str 

    initial_valid_value = 33
    final_valid_value = 126
    shift = generate_key()
    final_password = ''
    for letter in password:
        initial_ascii_num = ord(letter)
        final_ascii_num = initial_ascii_num + shift

        if final_ascii_num > 126:
            final_ascii_num = initial_valid_value + (final_ascii_num - final_valid_value - 1)

        letter = chr(final_ascii_num)

        final_password += letter


    return final_password 


def list_strip(lst: list) -> list:
    """
        returns the list but with each element stipped of unnecessary spaces before or after it

        Args:
            lst (list): the input list given
        
        Returns:
            stripped_lst (lst): the input list but each element is stripped
    """
    assert type(lst) == list

    stripped_lst = []

    for item in lst:
        item = item.strip()
        stripped_lst.append(item)

    return stripped_lst

def string_to_user(txt: str) -> tuple:
    """
        turns a string that contains formatted use information into a tuple where the first element is the username and 
        the second element is a dictionary that contains the users information

        Args:
            txt (str): the formatted user information
        
        Returns:
            (tuple): the tuple that contains formatted use information into a tuple where the first element is the username and 
            the second element is a dictionary that contains the users information
    """
    assert type(txt) == str

    final_dict = {}
    txt_list = txt.split('|')

    name_pass_bio = txt_list[0]
    name_pass__bio_list = name_pass_bio.split(',')
    name_pass__bio_list = list_strip(name_pass__bio_list)

    friends = txt_list[1]
    friends_list = friends.split(',')
    friends_list = list_strip(friends_list)

    name = name_pass__bio_list[0]
    password = name_pass__bio_list[1]
    bio = name_pass__bio_list[2]
    country = name_pass__bio_list[3]

    password_encrypted = encrypt_password(password)

    final_dict['password'] = password_encrypted
    final_dict['bio'] = bio
    final_dict['country'] = country
    final_dict['friends'] = friends_list


    return (name, final_dict)


def initialize_social_network_from_file(file_name: str) -> dict | int:
    """
        turns a given file into a dictionary that contains the user's information

        Args:
            file_name (str): the name of the file that contains the formatted user information
        
        Returns:
            final_dict(dict): the dictionary that contains the user's information
    """
    assert type(file_name) == str

    final_dict = {}
    file = open(file_name, 'r')
    output_list = file.readlines()
    file.close
    user_list = []
    for line in output_list:
        output_tuple = string_to_user(line)
        name = output_tuple[0]
        
        info_dict = output_tuple[1]
        final_dict[name] = info_dict

        if name in user_list:
            print(error_to_string(ERROR_DUPLICATE_USER))
            return 0
        user_list.append(name)

    return final_dict


def authenticate_user(username: str, password: str, social_dict: dict) -> bool:
    """
        authenticates a user based on their username and password

        Args:
            username (str): the input username
            password (str): the input password
            social_dict (str): the input dictionary
        
        Returns:
            (bool): returns true if the input information matches the information in the file, and false if the user input information does
            not match the information in the file
    """
    assert type(username) == str
    assert type(password) == str
    assert type(social_dict) == dict

    if username not in social_dict:
        return False
    if encrypt_password(password) != social_dict[username]['password']:
        return False
    
    
    return True



def add_friend(self_user: str, self_pass: str, friend_user: str, social_dict: dict):
    """
        adds a friend to the users friend list

        Args:
            self_user (str): the username of the person who is adding a friend
            self_pass (str): the password of the user
            friend_user (str): the username of the friend that will be added
            social_dict (dict): the input dictionary
        
        Returns:
            None
    """
    assert type(self_user) == str
    assert type(self_pass) == str
    assert type(friend_user) == str
    assert type(social_dict) == dict

    if authenticate_user(self_user, self_pass, social_dict) == False:
        print(error_to_string(ERROR_FAILED_AUTHENTICATION))
        return ERROR_FAILED_AUTHENTICATION
    
    if friend_user in social_dict[self_user]['friends']:
        print(error_to_string(ERROR_FRIEND_ALREADY_FOUND))
        return ERROR_FRIEND_ALREADY_FOUND
    
    if friend_user not in social_dict:
        print(error_to_string(ERROR_USER_NOT_FOUND))
        return ERROR_USER_NOT_FOUND
    
    if self_user == friend_user:
        return None

    social_dict[self_user]['friends'].append(friend_user) 
    social_dict[friend_user]['friends'].append(self_user)




def get_friend_index(self_user: str, friend_user: str, social_dict: dict) -> int:
    """
        gets the index value of a friend in the user's friend list

        Args:
            self_user (str): the input username
            friend_user (str): the username of the friend
            social_dict (str): the input dictionary
        
        Returns:
            friend_index (int): the index value of the friend in the user's friend list
    """
    assert type(self_user) == str
    assert type(friend_user) == str
    assert type(social_dict) == dict

    if friend_user not in social_dict[self_user]['friends']:
        return -1
    
    friend_list = social_dict[self_user]['friends']
    
    
    for i in range(len(friend_list)):
        if friend_user == friend_list[i]:
            friend_index = i
    
    return friend_index



